/**
 * @lang zh-CN 通用 CSS 变量注入模板适配器（`ADR-005` / `W-tb-P9`）：面向 Vue/React/纯 HTML 等任意栈的
 *   "接入即用"产物——hia-tokens.css（完整 HIA 令牌变量）+ README.md（三场景接入示例）。纯函数，无 IO。
 * @lang en Generic CSS-variable injection-template adapter (`ADR-005` / `W-tb-P9`): drop-in artifacts for any stack
 *   (Vue/React/plain HTML) — hia-tokens.css (full HIA token variables) + README.md (three integration scenarios).
 *   Pure, IO-free.
 */
import type{ExportTarget,VirtualFile}from'./types.js';
import type{Theme}from'../types.js';
import{slugifyThemeName,fullTokenCss,commentSafe}from'./shared.js';

// 通用注入模板适配器主体：产出 hia-tokens.css + README.md 两文件。
// <lang zh-CN>README 的三场景示例（Vue 3 / React / 纯 HTML）只引用 --hia-* 变量名，不含主题具体色值，
//   因此内容对全部主题恒定；标题行插入主题名以提示来源。</lang>
// <lang en>The README's three scenarios (Vue 3 / React / plain HTML) reference only --hia-* variable names and no
//   concrete theme colors, so its body is theme-invariant; the title line embeds the theme name for provenance.</lang>
function injectTemplateFiles(theme:Theme):VirtualFile[]{
  // hia-tokens.css：完整令牌变量文件（颜色/渐变 :root 块 + 字体/间距 :root 块），头部给最短接入示例。
  // <lang zh-CN>与 Tailwind 适配器的 tokens.css 同一生成器（fullTokenCss），仅头注释面向通用栈。</lang>
  // <lang en>Same generator as the Tailwind adapter's tokens.css (fullTokenCss); the header comment targets generic stacks.</lang>
  const tokensCss=fullTokenCss(theme,`/* HIA Theme Builder tokens — ${commentSafe(theme.name)}
 * Drop-in design tokens. Import once, then use any variable:
 *   color: var(--hia-primary-600);
 *   background: var(--hia-gradient-carousel);
 *   font-family: var(--hia-font-body); padding: var(--hia-space-2);
 */`);
  // README.md：三场景接入说明（Vue 3 / React / 纯 HTML），双语叙述。
  // <lang zh-CN>示例保持最小可运行：一行引入 + 一处消费；打包器差异（入口引入 vs link 标签）分别给出。</lang>
  // <lang en>Minimal runnable snippets: one import + one usage per scenario, covering bundler entry import vs link tag.</lang>
  const readme=`# ${theme.name} — HIA Tokens 接入指南 / Integration Guide

> 由 HIA Theme Builder 生成 / Generated by HIA Theme Builder。

## 文件 / Files

- \`hia-tokens.css\`：全部 HIA 设计令牌（颜色 10 档 + 自定义色阶、渐变、字体、字号、间距）。
  All HIA design tokens (10-step colors + custom shades, gradients, fonts, font sizes, spacing).

## 场景一：Vue 3（Vite 等打包器）

\`\`\`ts
// src/main.ts —— 引入一次即可 / import once
import './hia-tokens.css';
\`\`\`

\`\`\`vue
<style scoped>
.hero {
  /* 降级链（W-tb-P37）：color 先行垫底，image 失败时仍有纯色 / Degradation chain: colour first, image second */
  background-color: var(--hia-primary-500);
  background-image: var(--hia-gradient-carousel);
  color: var(--hia-primary-700);
  padding: var(--hia-space-3);
}
</style>
\`\`\`

## 场景二：React（CRA / Vite）

\`\`\`tsx
// src/index.tsx —— 引入一次即可 / import once
import './hia-tokens.css';

export function Card() {
  return (
    <div style={{
      background: 'var(--hia-primary-50)',
      color: 'var(--hia-primary-900)',
      fontFamily: 'var(--hia-font-body)',
      fontSize: 'var(--hia-fs-h3)'
    }}>HIA themed card</div>
  );
}
\`\`\`

## 场景三：纯 HTML

\`\`\`html
<link rel="stylesheet" href="./hia-tokens.css">
<style>
  /* 降级链：先 color 后 image / Degradation chain: colour first, image second */
  .banner { background-color: var(--hia-secondary-400); background-image: var(--hia-gradient-banner); color: var(--hia-secondary-900); }
</style>
\`\`\`

## 提示 / Notes

- 变量名规则 / Naming: \`--hia-primary-<shade>\`（shade 为 50–900 标准档或渐变引用的自定义档）；
- 明暗适配：在 \`html.dark\` 等作用域内覆写同批变量即可，无需改组件 / override the same vars under a scope like \`html.dark\`;
- 主题再生成时请整体替换本文件，避免手工修改丢失 / regenerate the whole file from HIA Theme Builder rather than hand-editing.
- **降级链**（W-tb-P37）：渐变/图片背景一律"先 \`background-color\` 纯色垫底、后 \`background-image\`"，渐变变量自身也携带起始色垫底层；任何一层失效都不露底色 / **Degradation chain**: gradient/image backgrounds pair a solid \`background-color\` with \`background-image\`; gradient vars also carry a start-colour underlay, so no layer failure exposes the bare container.
`;
  // 固定两文件顺序：tokens.css 在前（主产物）。
  // <lang zh-CN>路径为 ZIP 内相对根路径。</lang>
  // <lang en>Paths are ZIP-root-relative.</lang>
  return[
    {path:'hia-tokens.css',content:tokensCss},
    {path:'README.md',content:readme}
  ];
}

// 通用注入模板导出目标（注册表条目）。
// <lang zh-CN>面向"既有工程接入变量"的场景；archiveName 用主题 slug 命名。</lang>
// <lang en>For integrating variables into existing projects; archiveName uses the theme slug.</lang>
export const injectTemplateTarget:ExportTarget={
  id:'css-inject',
  name:'通用注入模板（ZIP）',
  nameEn:'Generic Inject Template (ZIP)',
  notes:'生成 hia-tokens.css（全部 HIA 令牌变量）与 README.md（Vue/React/纯 HTML 三场景接入示例），适合任意既有工程。',
  notesEn:'Emits hia-tokens.css (all HIA token variables) and README.md (Vue/React/plain-HTML integration examples) for any existing project.',
  archiveName:theme=>`hia-inject-${slugifyThemeName(theme.name)}.zip`,
  files:injectTemplateFiles
};
