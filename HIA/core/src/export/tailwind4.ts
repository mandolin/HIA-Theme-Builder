/**
 * @lang zh-CN Tailwind v4 适配器（`W-tb-P37`）：生成 **CSS-first** 的 `@theme` 块（app.css），
 *   把主题令牌直接定义为 Tailwind v4 主题变量——`--color-*` 生成 utilities（`bg-primary-500` 等），
 *   `--radius-*`/`--shadow-*` 接入 `rounded-*`/`shadow-*`。这是 v4 的一等形态；v3 `config.js`
 *   适配器保留为兼容形态（ADR-005 清单追加条目）。
 * @lang en Tailwind v4 adapter (`W-tb-P37`): emits a **CSS-first** `@theme` block (app.css) defining theme
 *   tokens as Tailwind v4 theme variables — `--color-*` generate utilities (`bg-primary-500`…), while
 *   `--radius-*`/`--shadow-*` power `rounded-*`/`shadow-*`. This is the v4 first-class form; the v3
 *   `config.js` adapter stays as the compatibility form (added to the ADR-005 registry).
 */
import type{ExportTarget,VirtualFile}from'./types.js';
import type{Theme}from'../types.js';
import{collectCustomShades}from'../gradient/render.js';
import{radiusSequence,shadowCss}from'../token/radius.js';
import{slugifyThemeName,commentSafe}from'./shared.js';

// 单色族 @theme 行：DEFAULT 之外的 10 档 + 自定义档（与 v3/CSS/JSON 同源）。
// <lang en>One family's @theme lines: the 10 steps plus custom shades (same source as v3/CSS/JSON).</lang>
function themeColorLines(prefix:string,scale:Record<string,string>,custom:Record<string,string>,base:string):string[]{
  return[
    `  --color-${prefix}: ${base};`,
    ...Object.entries(scale).map(([k,v])=>`  --color-${prefix}-${k}: ${v};`),
    ...Object.entries(custom).map(([k,v])=>`  --color-${prefix}-${k}: ${v};`)
  ];
}

/**
 * @lang zh-CN v4 适配器主体：产出单个 app.css（@theme 块 + 消费说明注释）。
 *   语义状态色、圆角、阴影随主题携带时输出；渐变以 CSS 变量 `--gradient-*` 形态放在 :root
 *   （@theme 只收静态值，渐变引用色阶时保持 var() 动态性）。
 * @lang en v4 adapter body: a single app.css (@theme block + usage comments). Semantic colours, radius and
 *   shadow emit when carried; gradients stay in :root as `--gradient-*` vars because @theme takes static
 *   values and gradients must keep referencing live scale vars.
 */
function tailwindV4Files(theme:Theme):VirtualFile[]{
  const custom=collectCustomShades(theme);
  const radius=radiusSequence(theme.radius);
  const shadows=shadowCss(theme.shadow,theme.primary.value);
  const colorLines=[
    ...themeColorLines('primary',theme.primary.scale,custom.primary,theme.primary.value),
    ...themeColorLines('secondary',theme.secondary.scale,custom.secondary,theme.secondary.value),
    ...(theme.thirdColor?themeColorLines('third',theme.thirdColor.scale,{},theme.thirdColor.value):[]),
    ...theme.auxiliary.flatMap((aux,i)=>themeColorLines(`aux${i}`,aux.scale,{},aux.value)),
    // 语义状态色（ADR-012）：仅主题携带时输出。
    // <lang en>Semantic statuses (ADR-012): emitted only when the theme carries them.</lang>
    ...(theme.semantic?(Object.keys(theme.semantic)as Array<keyof NonNullable<typeof theme.semantic>>).flatMap(k=>themeColorLines(k,theme.semantic![k].scale,{},theme.semantic![k].value)):[])
  ];
  const radiusLines=(Object.entries(radius)as[string,number][]).map(([k,v])=>`  --radius-${k}: ${v}px;`);
  const shadowLines=(Object.entries(shadows)as[string,string][]).map(([k,v])=>`  --shadow-${k}: ${JSON.stringify(v).replace(/"/g,'')};`);
  const gradientLines=Object.entries(theme.gradients)
    .filter(([,c])=>c)
    .map(([k])=>`  --gradient-${k}: var(--hia-gradient-${k});`);
  const css=`/* HIA Theme Builder — Tailwind v4 @theme tokens — ${commentSafe(theme.name)}
 * Generated by HIA Theme Builder (W-tb-P37 / ADR-005). Import in your main CSS:
 *   @import "app.css";
 * Utilities: bg-primary-500 · text-success-700 · rounded-md · shadow-lg · (gradients via var(--gradient-*))
 */
@theme {
${colorLines.join('\n')}
${radiusLines.join('\n')}
${shadowLines.join('\n')}
}

:root {
${gradientLines.join('\n')}
}
`;
  return[{path:'app.css',content:css}];
}

/** @lang zh-CN Tailwind v4 导出目标（注册表条目）。 @lang en Tailwind v4 export target (registry entry). */
export const tailwindV4Target:ExportTarget={
  id:'tailwind-v4',
  name:'Tailwind v4 @theme（ZIP）',
  nameEn:'Tailwind v4 @theme (ZIP)',
  notes:'生成 CSS-first 的 app.css：@theme 定义 --color-*/--radius-*/--shadow-*（v4 一等形态）；渐变经 var() 动态引用。',
  notesEn:'Emits a CSS-first app.css: @theme defines --color-*/--radius-*/--shadow-* (v4 first-class); gradients referenced dynamically via var().',
  archiveName:theme=>`hia-tailwind-v4-${slugifyThemeName(theme.name)}.zip`,
  files:tailwindV4Files
};
