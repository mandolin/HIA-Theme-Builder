/**
 * @lang zh-CN Tailwind 适配器（`ADR-005` / `W-tb-P9`）：生成 tailwind.config.js（CommonJS，含主副色全档 +
 *   ADR-004 自定义色阶 + 字体族透传）与 tokens.css（CSS 变量形态，供 Tailwind v4 @theme 或任意集成）。纯函数，无 IO。
 * @lang en Tailwind adapter (`ADR-005` / `W-tb-P9`): emits tailwind.config.js (CommonJS, with full primary/secondary
 *   scales + ADR-004 custom shades + fontFamily passthrough) and tokens.css (CSS variable form for Tailwind v4
 *   @theme or any integration). Pure, IO-free.
 */
import type{ExportTarget,VirtualFile}from'./types.js';
import type{Theme}from'../types.js';
import{collectCustomShades}from'../gradient/render.js';
import{slugifyThemeName,fullTokenCss,commentSafe}from'./shared.js';

// 生成单色族的 Tailwind colors 子对象：DEFAULT=基色，标准 10 档 + 自定义色阶附加键。
// <lang zh-CN>档位键加引号（'50'…'900'/'650'），保证 JS 对象字面量合法且键序与 SHADE_KEYS 一致；
//   自定义档与 CSS/JSON/WP 导出同源（collectCustomShades），四处产物一致。</lang>
// <lang en>Shade keys are quoted ('50'…'900'/'650') keeping the object literal valid and SHADE_KEYS ordering;
//   custom shades share the source (collectCustomShades) with CSS/JSON/WP exports.</lang>
function familyColors(scale:Record<string,string>,custom:Record<string,string>,base:string):string{
  // 拼装条目行：先 DEFAULT，再标准 10 档，最后自定义档；两层缩进对齐 config 结构。
  // <lang zh-CN>统一单引号风格，便于 eval 断言与 tailwind 加载。</lang>
  // <lang en>Uniform single-quote style, easy to assert via eval and load in Tailwind.</lang>
  const lines=[
    `      DEFAULT: '${base}'`,
    ...Object.entries(scale).map(([k,v])=>`      '${k}': '${v}'`),
    ...Object.entries(custom).map(([k,v])=>`      '${k}': '${v}'`)
  ];
  return`{\n${lines.join(',\n')}\n    }`;
}

// Tailwind 配置适配器主体：产出 tailwind.config.js + tokens.css 两文件。
// <lang zh-CN>config 以 CommonJS 导出（兼容 Tailwind v3 生态默认加载方式）；fontFamily 直接透传字符串栈
//   （Tailwind 接受字符串或数组）；heading 为 'inherit' 时透传原值并注释说明按需覆写。</lang>
// <lang en>Config is CommonJS (Tailwind v3's default loading); fontFamily passes through string stacks (Tailwind
//   accepts strings or arrays); an 'inherit' heading is passed verbatim with a comment to override as needed.</lang>
function tailwindConfigFiles(theme:Theme):VirtualFile[]{
  // 自定义色阶（ADR-004）：与其它导出同源。
  // <lang zh-CN>仅收集渐变引用过的档位，避免导出无关插值档。</lang>
  // <lang en>Only shades referenced by gradients are collected, avoiding unrelated interpolated steps.</lang>
  const custom=collectCustomShades(theme);
  // tailwind.config.js：content 占位符由使用方按工程实际路径调整（注释说明）。
  // <lang zh-CN>extend 合并语义保证不影响既有 Tailwind 主题；bg-primary-650 等类名即时可用。</lang>
  // <lang en>extend merge semantics leave existing Tailwind theme intact; classes like bg-primary-650 work immediately.</lang>
  const configJs=`/** HIA Theme Builder tokens — ${commentSafe(theme.name)}
 *  Generated by HIA Theme Builder (W-tb-P9 / ADR-005). Adjust \`content\` to your project globs.
 *  Usage: bg-primary-500 · text-secondary-800 · custom shades like bg-primary-650 are included.
 *  @type {import('tailwindcss').Config}
 */
module.exports = {
  content: ['./**/*.{html,js,ts,jsx,tsx,vue}'],
  theme: {
    extend: {
      colors: {
${[
        `        primary: ${familyColors(theme.primary.scale,custom.primary,theme.primary.value)}`,
        `        secondary: ${familyColors(theme.secondary.scale,custom.secondary,theme.secondary.value)}`,
        ...(theme.thirdColor?[`        third: ${familyColors(theme.thirdColor.scale,{},theme.thirdColor.value)}`]:[]),
        ...theme.auxiliary.map((aux,i)=>`        aux${i}: ${familyColors(aux.scale,{},aux.value)}`)
      ].join(',\n')}
      },
      fontFamily: {
        body: ${JSON.stringify(theme.typography.fontFamily.body)},
        heading: ${JSON.stringify(theme.typography.fontFamily.heading)},
        mono: ${JSON.stringify(theme.typography.fontFamily.mono)}
      }
    }
  }
};
`;
  // tokens.css：CSS 变量形态（颜色/渐变 + 字体/间距两个 :root 块），头部给 Tailwind v4 @theme inline 示例。
  // <lang zh-CN>v4 CSS-first 配置可直接 @theme inline 引用这些变量，v3 项目亦可整文件引入后 var() 使用。</lang>
  // <lang en>For v4 CSS-first config, reference these vars via @theme inline; v3 projects can import the file and use var().</lang>
  const tokensCss=fullTokenCss(theme,`/* HIA Theme Builder tokens — ${commentSafe(theme.name)}
 * Tailwind v4 usage: @theme inline { --color-primary-500: var(--hia-primary-500); }
 * Any stack: import this file once, then use var(--hia-primary-500) etc.
 */`);
  // 固定两文件顺序：config 在前（主产物）。
  // <lang zh-CN>路径即 ZIP 内相对根路径。</lang>
  // <lang en>Paths are ZIP-root-relative.</lang>
  return[
    {path:'tailwind.config.js',content:configJs},
    {path:'tokens.css',content:tokensCss}
  ];
}

// Tailwind 配置导出目标（注册表条目）。
// <lang zh-CN>archiveName 用主题 slug 命名，web 层直接采用。</lang>
// <lang en>archiveName uses the theme slug; the web layer adopts it directly.</lang>
export const tailwindConfigTarget:ExportTarget={
  id:'tailwind-config',
  name:'Tailwind 配置（ZIP）',
  nameEn:'Tailwind Config (ZIP)',
  notes:'生成 tailwind.config.js（主副色全档 + 自定义色阶 + 字体族）与 tokens.css（CSS 变量/Tailwind v4 @theme）。',
  notesEn:'Emits tailwind.config.js (full scales + custom shades + fontFamily) and tokens.css (CSS vars / Tailwind v4 @theme).',
  archiveName:theme=>`hia-tailwind-${slugifyThemeName(theme.name)}.zip`,
  files:tailwindConfigFiles
};
